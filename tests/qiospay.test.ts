test("browser receipt recovery is scoped, discards corrupt data, and never hydrates voucher fields", () => {
  const data = new Map<string, string>();
  (globalThis as any).window = { sessionStorage: {
    getItem: (k: string) => data.get(k) ?? null,
    setItem: (k: string, v: string) => data.set(k, v),
    removeItem: (k: string) => data.delete(k),
    key: (i: number) => [...data.keys()][i] ?? null,
    get length() { return data.size; },
  } };
  try {
    const a = qrisRecoveryKey("user-1", 1), b = qrisRecoveryKey("user-2", 1);
    const payment = { provider: "qiospay", reference_id: "TEST-REF", qr_url: "data:image/png;base64,AA==",
      amount: 5123, base_amount: 5000, unique_code: 123, expires_at: new Date(Date.now() + 60_000).toISOString() };
    storeQrisRecovery(a, { ...payment, voucher_code: "DO-NOT-HYDRATE" } as any);
    assert.equal(readQrisRecovery(a)?.reference_id, "TEST-REF");
    assert.equal((readQrisRecovery(a) as any).voucher_code, undefined);
    assert.equal(readQrisRecovery(b), null);
    storeQrisRecovery(b, payment);
    clearQrisRecoveryForIdentity("user-1");
    assert.equal(readQrisRecovery(a), null);
    assert.ok(readQrisRecovery(b));
    storeQrisRecovery(a, { ...payment, qr_url: "javascript:alert(1)" });
    assert.equal(readQrisRecovery(a), null);
    assert.equal(data.has(a), false);
    storeQrisRecovery(a, { ...payment, provider: "sanpay", unique_code: 0, amount: 5000,
      qr_url: "https://api.qrserver.com/v1/create-qr-code/?size=300x300&data=test", expires_at: null } as any);
    assert.equal(readQrisRecovery(a), null, "Retired gateway receipts cannot reopen checkout");
    storeQrisRecovery(a, { ...payment, amount: 9999 });
    assert.equal(readQrisRecovery(a), null);
  } finally { delete (globalThis as any).window; }
});