test("credit normalization ignores debits; deduplication is stable for equivalent values", () => {
  const row = { amount: "5100", type: "CR", date: "2026-10-02 22:00:00", balance: "15100", brand_name: "TEST" };
  assert.equal(normalizeCredits("TEST", [{ ...row, type: "DB" }]).length, 0);
  assert.equal(normalizeCredits("TEST", [row])[0].key, normalizeCredits("TEST", [{ ...row, amount: 5100, balance: "15100.00", qris: "static" }])[0].key);
  assert.throws(() => normalizeCredits("TEST", [{ ...row, date: "invalid" }]));
  assert.throws(() => normalizeCredits("TEST", [{ ...row, amount: "5.5" }]));
  assert.throws(() => normalizeCredits("TEST", [{ ...row, balance: undefined }]));
  assert.throws(() => normalizeCredits("TEST", [{ ...row, balance: "not-a-balance" }]));
});
